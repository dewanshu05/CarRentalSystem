package com.carrental.model;

import java.io.Serializable;
import java.sql.Timestamp;

/**
 * Model: Car (Java Bean / POJO)
 * Represents the 'cars' table in the MySQL database.
 */
public class Car implements Serializable {
    private static final long serialVersionUID = 1L;

    private int carId;
    private String carModel;
    private String brand;
    private String category;
    private String registrationNumber;
    private double dailyRate;
    private String status; // 'AVAILABLE', 'RENTED', 'MAINTENANCE'
    private int seatingCapacity;
    private String fuelType;
    private Timestamp createdAt;

    // Default Constructor
    public Car() {
        this.status = "AVAILABLE";
        this.seatingCapacity = 5;
        this.fuelType = "Petrol";
    }

    // Constructor for creating a new Car (without carId, auto-generated by MySQL)
    public Car(String carModel, String brand, String category, String registrationNumber,
               double dailyRate, String status, int seatingCapacity, String fuelType) {
        this.carModel = carModel;
        this.brand = brand;
        this.category = category;
        this.registrationNumber = registrationNumber;
        this.dailyRate = dailyRate;
        this.status = status;
        this.seatingCapacity = seatingCapacity;
        this.fuelType = fuelType;
    }

    // Full Parameterized Constructor (for retrieving from Database)
    public Car(int carId, String carModel, String brand, String category, String registrationNumber,
               double dailyRate, String status, int seatingCapacity, String fuelType, Timestamp createdAt) {
        this.carId = carId;
        this.carModel = carModel;
        this.brand = brand;
        this.category = category;
        this.registrationNumber = registrationNumber;
        this.dailyRate = dailyRate;
        this.status = status;
        this.seatingCapacity = seatingCapacity;
        this.fuelType = fuelType;
        this.createdAt = createdAt;
    }

    // Getters and Setters
    public int getCarId() {
        return carId;
    }

    public void setCarId(int carId) {
        this.carId = carId;
    }

    public String getCarModel() {
        return carModel;
    }

    public void setCarModel(String carModel) {
        this.carModel = carModel;
    }

    public String getBrand() {
        return brand;
    }

    public void setBrand(String brand) {
        this.brand = brand;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public String getRegistrationNumber() {
        return registrationNumber;
    }

    public void setRegistrationNumber(String registrationNumber) {
        this.registrationNumber = registrationNumber;
    }

    public double getDailyRate() {
        return dailyRate;
    }

    public void setDailyRate(double dailyRate) {
        this.dailyRate = dailyRate;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public int getSeatingCapacity() {
        return seatingCapacity;
    }

    public void setSeatingCapacity(int seatingCapacity) {
        this.seatingCapacity = seatingCapacity;
    }

    public String getFuelType() {
        return fuelType;
    }

    public void setFuelType(String fuelType) {
        this.fuelType = fuelType;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    // Helper: Is car available for rent?
    public boolean isAvailable() {
        return "AVAILABLE".equalsIgnoreCase(this.status);
    }

    @Override
    public String toString() {
        return "Car [carId=" + carId + ", brand=" + brand + ", carModel=" + carModel
                + ", regNo=" + registrationNumber + ", dailyRate=" + dailyRate
                + ", status=" + status + "]";
    }
}
